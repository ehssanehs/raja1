export const catalogues: Record<Locale, Record<MessageKey, string>> = { en, fa };

export function isLocale(value: unknown): value is Locale {
  return value === 'fa' || value === 'en';
}

/** Translate with `{param}` interpolation and a safe fallback to the default locale. */
export function t(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  const template = catalogues[locale]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

/** Build a translator bound to a locale (used by bot handlers and web components). */
export function translator(locale: Locale): (key: MessageKey, params?: Record<string, string | number>) => string {
  return (key, params) => t(locale, key, params);
}

